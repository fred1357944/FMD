QString normalize(const QString &language)
{
    const QString trimmed = language.trimmed();
    if (trimmed.startsWith(QLatin1String("en"), Qt::CaseInsensitive))
        return QStringLiteral("en");
    return QStringLiteral("zh-TW");
}

QStringList codes()
{
    return {QStringLiteral("zh-TW"), QStringLiteral("en")};
}

QVariantMap strings(const QString &language)
{
    const QString code = normalize(language);
    QVariantMap out;
    const auto &table = catalog().value(code);
    for (auto it = table.constBegin(); it != table.constEnd(); ++it)
        out.insert(it.key(), it.value());
    return out;
}

QString t(const QString &language, const QString &key)
{
    const QString code = normalize(language);
    const auto &table = catalog().value(code);
    if (table.contains(key))
        return table.value(key);
    const auto &fallback = catalog().value(QStringLiteral("zh-TW"));
    return fallback.value(key, key);
}

